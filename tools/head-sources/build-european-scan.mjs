// Generates src/anatomy/europeanScanData.ts from the Lee Perry-Smith head scan (CC BY 3.0,
// Infinite-Realities / triplegangers.com; decimated glb from the three.js examples).
// Usage: node scripts/build-european-scan.mjs /path/to/LeePerrySmith.glb
// The scan is warped (landmark-based, near-uniform scale) into FaceR's canonical head frame so the shared
// FACS muscles, eyes, teeth, brows and hair work on it. Its eyelids are closed in the scan, so an almond
// opening is cut over each eye so the eyeballs show.
import fs from 'node:fs';

const glbPath = process.argv[2];
if (!glbPath) throw new Error('usage: node scripts/build-european-scan.mjs LeePerrySmith.glb');
const d = fs.readFileSync(glbPath);
const jl = d.readUInt32LE(12);
const j = JSON.parse(d.subarray(20, 20 + jl).toString());
const bin = d.subarray(20 + jl + 8);
const acc = (i, T, sz) => {
  const a = j.accessors[i], bv = j.bufferViews[a.bufferView];
  const off = bin.byteOffset + (bv.byteOffset || 0) + (a.byteOffset || 0);
  return new T(bin.buffer.slice(off, off + a.count * sz * T.BYTES_PER_ELEMENT));
};
const pr = j.meshes[0].primitives[0];
const P = acc(pr.attributes.POSITION, Float32Array, 3);
const I = acc(pr.indices, Uint16Array, 1);

// --- landmark warp scan -> canonical frame -------------------------------------------------
const YS = [-0.40, 0.45, 1.10, 1.65, 3.97];            // scan: chin, mouth seam, nose tip, eye line, head top
const YC = [-5.05, -2.5, -0.1, 1.86, 9.35];            // canonical equivalents
const KX = 3.3, KZ = 3.15, ZTIP_S = 2.59, ZTIP_C = 7.09, KY_EXT = 3.3;
function warpY(y) {
  if (y <= YS[0]) return YC[0] + (y - YS[0]) * KY_EXT;
  if (y >= YS[4]) return YC[4] + (y - YS[4]) * KY_EXT;
  for (let k = 0; k < 4; k++) if (y <= YS[k + 1]) { const t = (y - YS[k]) / (YS[k + 1] - YS[k]); return YC[k] + t * (YC[k + 1] - YC[k]); }
  return y;
}
const nV = P.length / 3;
const W = new Float32Array(P.length);
for (let i = 0; i < nV; i++) {
  W[i * 3] = P[i * 3] * KX;
  W[i * 3 + 1] = warpY(P[i * 3 + 1]);
  W[i * 3 + 2] = KZ * (P[i * 3 + 2] - ZTIP_S) + ZTIP_C;
}

// --- eye openings --------------------------------------------------------------------------
const EYE_X = Number(process.env.EYE_X ?? 2.2), EYE_Y = Number(process.env.EYE_Y ?? 1.82);
const EYE_HW = Number(process.env.EYE_HW ?? 0.95), EYE_HH = Number(process.env.EYE_HH ?? 0.4);
const NECK_Y = -11.0;
const keepTri = [];
let cutEye = 0, cutNeck = 0;
for (let t = 0; t < I.length; t += 3) {
  const a = I[t], b = I[t + 1], c = I[t + 2];
  const cx = (W[a * 3] + W[b * 3] + W[c * 3]) / 3, cy = (W[a * 3 + 1] + W[b * 3 + 1] + W[c * 3 + 1]) / 3;
  const cz = (W[a * 3 + 2] + W[b * 3 + 2] + W[c * 3 + 2]) / 3;
  if (Math.min(W[a * 3 + 1], W[b * 3 + 1], W[c * 3 + 1]) < NECK_Y - 0.8) { cutNeck++; continue; }
  const dx = (Math.abs(cx) - EYE_X) / EYE_HW, dy = (cy - EYE_Y) / EYE_HH;
  if (cz > 3 && dx * dx + dy * dy < 1) { cutEye++; continue; }
  keepTri.push(a, b, c);
}
// flat neck cut: clamp the few vertices below the cut line
for (const v of new Set(keepTri)) if (W[v * 3 + 1] < NECK_Y) W[v * 3 + 1] = NECK_Y;
// compact vertices
const remap = new Int32Array(nV).fill(-1); let n = 0;
for (const v of keepTri) if (remap[v] < 0) remap[v] = n++;
const outP = new Float32Array(n * 3), outI = new Int32Array(keepTri.length);
for (let i = 0; i < nV; i++) if (remap[i] >= 0) outP.set(W.subarray(i * 3, i * 3 + 3), remap[i] * 3);
for (let i = 0; i < keepTri.length; i++) outI[i] = remap[keepTri[i]];

// surface z around the eye openings (median of the ring just outside the opening) for placing the eyeballs
const ring = [];
for (let i = 0; i < n; i++) {
  const x = Math.abs(outP[i * 3]), y = outP[i * 3 + 1];
  const dx = (x - EYE_X) / EYE_HW, dy = (y - EYE_Y) / EYE_HH, r = Math.hypot(dx, dy);
  if (r > 1 && r < 1.2 && outP[i * 3 + 2] > 3) ring.push(outP[i * 3 + 2]);
}
ring.sort((a, b) => a - b);
const surf = ring.length ? ring[ring.length >> 1] : 5.5;
const cnt = ring.length;
console.error(`verts ${nV} -> ${n}, tris ${I.length / 3} -> ${outI.length / 3} (eye cut ${cutEye}, neck cut ${cutNeck}), rim z ${surf.toFixed(2)} (${cnt})`);

const f = (v) => Number(v.toFixed(4));
const out = `// Auto-generated by scripts/build-european-scan.mjs -- do not edit.
// Lee Perry-Smith "Infinite" head scan (Creative Commons Attribution 3.0, Infinite-Realities / triplegangers.com),
// warped into FaceR's canonical head frame, with an eye opening cut over each (closed) eye.

export const EUROPEAN_SCAN_EYE_X = ${EYE_X};
export const EUROPEAN_SCAN_EYE_Y = ${EYE_Y};
export const EUROPEAN_SCAN_EYE_RIM_Z = ${f(surf)};

export const EUROPEAN_SCAN_POSITIONS = new Float32Array([${Array.from(outP, f).join(',')}]);
export const EUROPEAN_SCAN_INDICES = new Int32Array([${Array.from(outI).join(',')}]);
`;
fs.writeFileSync(new URL('../src/anatomy/europeanScanData.ts', import.meta.url), out);
